/**
 * You already know `string`, `number`, `boolean` JS types - these are called "primitive" types
 * Also you know `object` and `array` types which are called "non-primitive" types
 * And there are two special primitive types in JavaScript: `null` and `undefined`
 */

/**
 * If you're declaring variable and not initializing it with some value, it's type by default will be `undefined`
 */

let a;
typeof a; // undefined

/**
 * So `undefined` type is default type of unassigned variables. Also there
 * is another special `null` type. By default variables are never can be `null` - `null` type can be only assigned to variable intentionally
 */

let a = null;
typeof a; // null

